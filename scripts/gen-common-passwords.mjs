#!/usr/bin/env node
// Writes apps/cms/src/utils/common-passwords.ts, the common-password list of
// the v0.27 password baseline: the 5000 most frequent passwords of at least
// 12 characters in SecLists' Pwdb_top-1000000 (MIT), lowercased and
// deduplicated, in frequency order. Pinned to one SecLists commit and the
// file's sha256, so a re-run writes the same list. Run by hand:
//   node scripts/gen-common-passwords.mjs
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const COMMIT = "4c0fd59432ab8508edc23b3c880127edb12e34d5";
const URL_ = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/Passwords/Common-Credentials/Pwdb_top-1000000.txt`;
const SHA256 = "e9a88f67aafe65496682dc374559ee714e978bee50314767494c3e37a18c9fc8";
const MIN_LENGTH = 12;
const MAX_ENTRIES = 5000;
const OUT = fileURLToPath(new URL("../apps/cms/src/utils/common-passwords.ts", import.meta.url));

const res = await fetch(URL_);
if (!res.ok) throw new Error(`download failed: ${res.status}`);
const bytes = Buffer.from(await res.arrayBuffer());
const sha = createHash("sha256").update(bytes).digest("hex");
if (sha !== SHA256) throw new Error(`unexpected sha256 ${sha}`);

const list = [];
const seen = new Set();
for (const line of bytes.toString("utf8").split("\n")) {
  const entry = line.replace(/\r$/, "").toLowerCase();
  if (Array.from(entry).length < MIN_LENGTH || seen.has(entry)) continue;
  seen.add(entry);
  list.push(entry);
  if (list.length === MAX_ENTRIES) break;
}

writeFileSync(
  OUT,
  `// Generated by scripts/gen-common-passwords.mjs; do not edit.\n` +
    `// The ${list.length} most frequent passwords of at least ${MIN_LENGTH} characters in\n` +
    `// SecLists Passwords/Common-Credentials/Pwdb_top-1000000.txt (MIT, commit ${COMMIT.slice(0, 12)}),\n` +
    `// lowercased and deduplicated. The cms only: never import it into the web.\n` +
    `export const COMMON_PASSWORDS: ReadonlySet<string> = new Set(${JSON.stringify(list, null, 0)});\n`,
);
console.log(`wrote ${list.length} entries to ${OUT}`);
